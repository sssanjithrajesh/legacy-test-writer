"""Turn accepted observations into JUnit 5 tests.

One test class per legacy class. Method names are slugs of the scenario label so a failure
reads as the input that broke, not a number. Exception tests use assertThrows(Class, ...) and
never the message.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from ltw.review import Verdict
from ltw.scenario import jstr, slug
from ltw.toolchain import GENERATED_TESTS, PACKAGE


def _java_expected(obs) -> str:
    if obs.type == "null" or (obs.value is None and obs.type != "java.lang.String"):
        return "null"
    if obs.type in ("java.lang.Integer", "int"):
        return f"Integer.valueOf({obs.value})"
    if obs.type in ("java.lang.Boolean", "boolean"):
        return "Boolean.TRUE" if obs.value == "true" else "Boolean.FALSE"
    if obs.type in ("java.lang.Long", "long"):
        return f"Long.valueOf({obs.value}L)"
    return jstr(obs.value)


def _method_name(v: Verdict) -> str:
    s = v.observed.scenario
    return f"{s.id.replace('-', '_')}_{slug(s.label)}"


def _test_method(v: Verdict) -> str:
    s = v.observed.scenario
    obs = v.observed.first
    setup = "\n        ".join(s.setup)
    indent_setup = f"        {setup}\n" if setup else ""
    name = _method_name(v)
    if obs.kind == "OK":
        expected = _java_expected(obs)
        return (
            f"    @Test\n    void {name}() throws Exception {{\n"
            f"{indent_setup}        assertEquals({expected}, {s.call});\n    }}\n"
        )
    ex = obs.type
    return (
        f"    @Test\n    void {name}() throws Exception {{\n"
        f"{indent_setup}        assertThrows({ex}.class, () -> {s.call});\n    }}\n"
    )


def render_class(class_name: str, verdicts: list[Verdict]) -> str:
    methods = "\n".join(_test_method(v) for v in verdicts)
    imports = {
        "import org.junit.jupiter.api.Test;",
        "import static org.junit.jupiter.api.Assertions.assertEquals;",
        "import static org.junit.jupiter.api.Assertions.assertThrows;",
        "import org.apache.commons.codec.EncoderException;",
        "import org.apache.commons.codec.StringEncoder;",
    }
    return (
        f"package {PACKAGE};\n\n"
        + "\n".join(sorted(imports))
        + "\n\n"
        + f"/** Characterization tests generated by legacy-test-writer. Do not hand-edit. */\n"
        f"class {class_name}CharacterizationTest {{\n\n"
        f"{methods}"
        f"}}\n"
    )


def emit(verdicts: list[Verdict], dest: Path = GENERATED_TESTS) -> list[Path]:
    by_cls: dict[str, list[Verdict]] = defaultdict(list)
    for v in verdicts:
        if v.action == "emit":
            by_cls[v.observed.scenario.cls].append(v)
    written = []
    package_dir = dest.joinpath(*PACKAGE.split("."))
    if package_dir.exists():
        for old in package_dir.glob("*CharacterizationTest.java"):
            old.unlink()
    package_dir.mkdir(parents=True, exist_ok=True)
    for cls, rows in sorted(by_cls.items()):
        path = package_dir / f"{cls}CharacterizationTest.java"
        path.write_text(render_class(cls, rows), encoding="ascii")
        written.append(path)
    return written
